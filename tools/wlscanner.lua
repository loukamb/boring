-- Generate C protocol headers from Wayland protocol XML, in Lua.
--
-- Produces the declarations `wayland-scanner server-header|client-header`
-- would (interface externs, enums, request/listener structs) minus the static
-- inline helpers, which LuaJIT can't use anyway. Used by tools/ffi_gen.lua so
-- that wlroots headers that `#include "foo-protocol.h"` preprocess, and so
-- the bindings carry protocol enums and structs, without wayland-scanner.

package.path = "./?/init.lua;./?.lua;" .. package.path

local protocol = require("shared.wayland.protocol")
local cdecl = require("tools.cdecl")

local wlscanner = {}

local function param_name(name)
    if cdecl.keywords[name] then return name .. "_" end
    return name
end

local scalar = {
    int = "int32_t",
    uint = "uint32_t",
    fixed = "wl_fixed_t",
    string = "const char *",
    array = "struct wl_array *",
    fd = "int32_t",
}

-- C parameter list for a message's arguments.
local function params(args, side)
    local out = {}
    for _, arg in ipairs(args) do
        local name = param_name(arg.name)
        local t = arg.type
        if scalar[t] then
            local ctype = scalar[t]
            out[#out + 1] = ctype .. (ctype:sub(-1) == "*" and "" or " ") .. name
        elseif t == "object" then
            if side == "server" then
                out[#out + 1] = "struct wl_resource *" .. name
            elseif arg.interface then
                out[#out + 1] = "struct " .. arg.interface .. " *" .. name
            else
                out[#out + 1] = "void *" .. name
            end
        elseif t == "new_id" then
            if side == "server" then
                if not arg.interface then
                    out[#out + 1] = "const char *interface"
                    out[#out + 1] = "uint32_t version"
                end
                out[#out + 1] = "uint32_t " .. name
            else
                -- Only events reach client listeners; new objects arrive typed.
                out[#out + 1] = "struct " .. (arg.interface or "wl_proxy") .. " *" .. name
            end
        else
            error("wlscanner: unknown argument type " .. tostring(t))
        end
    end
    return out
end

local function messages(list)
    local out = {}
    local i = 0
    while list[i] do
        out[#out + 1] = list[i]
        i = i + 1
    end
    return out
end

--- C header text for a parsed protocol.
---@param proto table result of shared.wayland.protocol.parse
---@param side "server"|"client"
---@return string
function wlscanner.header(proto, side)
    assert(side == "server" or side == "client", "side must be server or client")
    local lines = {
        "/* Generated by tools/wlscanner.lua from the " .. tostring(proto.name) .. " protocol. */",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "#include <wayland-util.h>",
    }
    if side == "server" then
        lines[#lines + 1] = "struct wl_client;"
        lines[#lines + 1] = "struct wl_resource;"
    end

    -- Forward declarations for every interface named, ours or foreign.
    local declared = {}
    local function forward(name)
        if name and not declared[name] then
            declared[name] = true
            lines[#lines + 1] = "struct " .. name .. ";"
        end
    end
    for _, iface in ipairs(proto.interface_list) do
        forward(iface.name)
        for _, list in ipairs({ iface.requests, iface.events }) do
            for _, msg in ipairs(messages(list)) do
                for _, arg in ipairs(msg.args) do forward(arg.interface) end
            end
        end
    end
    for _, iface in ipairs(proto.interface_list) do
        lines[#lines + 1] = "extern const struct wl_interface " .. iface.name .. "_interface;"
    end

    for _, iface in ipairs(proto.interface_list) do
        for _, enum in ipairs(iface.enum_list) do
            local prefix = (iface.name .. "_" .. enum.name):upper()
            local entries = {}
            for _, e in ipairs(enum.entries) do
                entries[#entries + 1] = string.format("\t%s_%s = %d,", prefix, e.name:upper(), e.value)
            end
            lines[#lines + 1] = "enum " .. iface.name .. "_" .. enum.name .. " {"
            lines[#lines + 1] = table.concat(entries, "\n")
            lines[#lines + 1] = "};"
        end

        local list, struct_name, first
        if side == "server" then
            list, struct_name = iface.requests, iface.name .. "_interface"
            first = "struct wl_client *client, struct wl_resource *resource"
        else
            list, struct_name = iface.events, iface.name .. "_listener"
            first = "void *data, struct " .. iface.name .. " *" .. param_name(iface.name)
        end
        local msgs = messages(list)
        if #msgs > 0 then
            lines[#lines + 1] = "struct " .. struct_name .. " {"
            for _, msg in ipairs(msgs) do
                local p = params(msg.args, side)
                table.insert(p, 1, first)
                lines[#lines + 1] = string.format("\tvoid (*%s)(%s);", param_name(msg.name), table.concat(p, ", "))
            end
            lines[#lines + 1] = "};"
        end
    end

    return table.concat(lines, "\n") .. "\n"
end

--- Header text for a protocol XML file.
function wlscanner.header_from_file(path, side)
    local proto, err = protocol.parse_file(path)
    if not proto then error("wlscanner: " .. tostring(err)) end
    return wlscanner.header(proto, side)
end

return wlscanner
